classdef Axis < hdng.diagrams.features.Geometry
    %Axis Summary.  
    %   Detailed description 
    
    properties
        axis_scale
        axis_scale_feature
    end
    
    properties (Dependent, Transient)
        configuration
    end
    
    methods

        function result = get.configuration(obj)
            result = obj.feature_declarator.configuration;
        end
        
        function obj = Axis(varargin)
            obj@hdng.diagrams.features.Geometry(varargin{:});

            options = hdng.utilities.parse_struct_from_varargin(varargin{:});


            if ~isfield(options, 'parent_stack')
                options.parent_stack = {};
            end
           
            obj.values_by_identifier.stroke = 'black';
            obj.values_by_identifier.stroke_width = '3';

            obj.axis_scale = [];
            obj.axis_scale_feature = [];

            [obj.axis_scale, obj.axis_scale_feature] = obj.lookup_scale(obj.feature_declarator.scale_identifier, options.parent_stack);
        end
        

        function next_child = render(obj, n_visit, render_context, base, parents, siblings)
            next_child = render@hdng.diagrams.features.Geometry(obj, n_visit, ...
                render_context, base, parents, siblings);
            
            if n_visit ~= 1 || isempty(obj.axis_scale)
                return;
            end
            
            render_options = obj.define_render_options();
            render_options = hdng.utilities.struct_to_name_value_sequence(render_options);
            
            baseline = obj.configuration.baseline;
            rules = obj.configuration.rules;
            labels = obj.configuration.labels;

            domain = obj.axis_scale.domain;
            scaled_domain = obj.axis_scale.apply({domain(1), domain(2)});
            scaled_domain = cell2mat(scaled_domain);
            offset = obj.values_by_identifier.offset;

            switch obj.configuration.orientation

                case 'bottom'
        
                    if baseline.show
                        
                        render_context.renderer.render_line(...
                            scaled_domain(1), ...
                            scaled_domain(2), ...
                            offset, ...
                            offset, ...
                            render_context, ...
                            render_options{:} ...
                        );
                    end

                    if rules.show
                        
                        
                        positions = obj.axis_scale.apply(rules.at);

                        for index=1:numel(rules.at)
                            value = rules.at{index};
                            position = positions{index};
                            
                            render_context.renderer.render_line(...
                                position, ...
                                position, ...
                                0, ...
                                offset, ...
                                render_context, ...
                                render_options{:} ...
                            );
                    
                            render_context.renderer.render_text(...
                                position + 10, ...
                                offset - 10, ...
                                false, ...
                                false, ...
                                sprintf('%g', value), ...
                                render_context, ...
                                'fill', 'black', ...
                                'class', rules.label_style_class ...
                            );
                        end
                    end

                    if labels.show
                        
                        if labels.show_min_label

                            value = obj.axis_scale.domain(1);
                            value = sprintf('%.4f', value);
                            position = obj.axis_scale.defined_range(1);
                    
                            render_context.renderer.render_text(...
                                position + 10, ...
                                offset - 10, ...
                                false, ...
                                false, ...
                                value, ...
                                render_context, ...
                                'fill', 'black', ...
                                'class', labels.style_class ...
                            );
                        end

                        if labels.show_max_label
                    
                            value = obj.axis_scale.domain(2);
                            value = sprintf('%.4f', value);
                            position = obj.axis_scale.defined_range(2);
                            
                            line = render_context.renderer.layout_text(value, labels.style, Inf, 'start');

                            render_context.renderer.render_text(...
                                position - 10 - line.width, ...
                                offset - 10, ...
                                false, ...
                                false, ...
                                value, ...
                                render_context, ...
                                'fill', 'black', ...
                                'class', labels.style_class ...
                            );
                        end

                    end


                case 'right'
        
                    if baseline.show
                        
                        render_context.renderer.render_line(...
                            offset, ...
                            offset, ...
                            scaled_domain(1), ...
                            scaled_domain(2), ...
                            render_context, ...
                            render_options{:} ...
                        );
                    end

                    if rules.show
                        
                        
                        positions = obj.axis_scale.apply(rules.at);

                        for index=1:numel(rules.at)
                            value = rules.at{index};
                            position = positions{index};
                            
                            render_context.renderer.render_line(...
                                0, ...
                                offset, ...
                                position, ...
                                position, ...
                                render_context, ...
                                render_options{:} ...
                            );
                    
                            render_context.renderer.render_text(...
                                offset - 10, ...
                                position + 10, ...
                                false, ...
                                false, ...
                                sprintf('%g', value), ...
                                render_context, ...
                                'fill', 'black', ...
                                'class', rules.label_style_class ...
                            );
                        end
                    end

                    if labels.show
                        
                        if labels.show_min_label

                            value = obj.axis_scale.domain(1);
                            value = sprintf('%.4f', value);
                            position = obj.axis_scale.defined_range(1);
                    
                            render_context.renderer.render_text(...
                                offset - 10, ...
                                position + 10, ...
                                false, ...
                                false, ...
                                value, ...
                                render_context, ...
                                'fill', 'black', ...
                                'class', labels.style_class ...
                            );
                        end

                        if labels.show_max_label
                    
                            value = obj.axis_scale.domain(2);
                            value = sprintf('%.4f', value);
                            position = obj.axis_scale.defined_range(2);
                            
                            line = render_context.renderer.layout_text(value, labels.style, Inf, 'start');

                            render_context.renderer.render_text(...
                                offset - 10, ...
                                position - 10 - line.height, ...
                                false, ...
                                false, ...
                                value, ...
                                render_context, ...
                                'fill', 'black', ...
                                'class', labels.style_class ...
                            );
                        end
                    end
            end
        end
        
    end
end
            
