function result = format_css_definition(selectors, dictionary)
    
    result = hdng.diagrams.utilities.format_css_attributes(dictionary, false);

    selectors = join(selectors, ', ');
    selectors = selectors{1};

    result = sprintf('%s {\n%s\n}\n', selectors, result);
end